  /// Returns the localized Surah name without prefix (e.g. "Al-Fatiha" or "الفاتحة").
  static String nameFor(int surahNumber, {String languageCode = 'en'}) {
    if (surahNumber < 1 || surahNumber > 114) {
      return '#$surahNumber';
    }
    final idx = surahNumber - 1;
    switch (languageCode.toLowerCase()) {
      case 'ar':
        return _arabic[idx];
      case 'am':
        return _amharic[idx];
      default:
        return _english[idx];
    }
  }

  /// Returns the localized Surah label with prefix (e.g. "Surah Al-Fatiha").
  static String formatted(int surahNumber, {String languageCode = 'en'}) {
    final name = nameFor(surahNumber, languageCode: languageCode);
    switch (languageCode.toLowerCase()) {
      case 'ar':
        return 'سورة $name';
      case 'am':
        return 'ሱራ $name';
      default:
        return 'Surah $name';
    }
  }
